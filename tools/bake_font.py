#!/usr/bin/env python3
"""Bake the handful of caption strings used by the intro into a tiny 1-bit glyph
font (src/font.h), rows byte-aligned. Only glyphs that are actually used are stored. The intro turns
this bitmap into a signed distance field at startup, so titles stay crisp at 4K.

Font: Cinzel (SIL Open Font License 1.1) - https://github.com/NDISCOVER/Cinzel, vendored in tools/fonts
Usage: python3 tools/bake_font.py [path/to/Cinzel.ttf]   (needs Pillow)
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

LINES = [
    "CATHEDRA",
    "A 64K INTRO",
    "I  ASCENSIO",
    "II  NAVIS",
    "III  COR",
    "IV  ORBIS",
    "CODE  SHADERS  SYNTH  BY GROK & OPUS",
    "V  SOL",
]
GH = 60          # glyph cell height in pixels
TRACK = 5        # extra letter spacing
font_path = sys.argv[1] if len(sys.argv) > 1 else \
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts", "Cinzel-VariableFont_wght.ttf")
font = ImageFont.truetype(font_path, 56)
try:
    font.set_variation_by_axes([600])
except Exception:
    pass
chars = sorted(set("".join(LINES)) - {" "})
asc, desc = font.getmetrics()
out = []
data = bytearray()
for ch in chars:
    l, t, r, b = font.getbbox(ch)
    w = max(1, r - l)
    img = Image.new("L", (w, GH), 0)
    ImageDraw.Draw(img).text((-l, (GH - asc) // 2 + 2), ch, font=font, fill=255)
    px = img.load()
    for x0 in range(0, w, 8):   # 1 bit per pixel in columns 8 px wide, each column top to bottom (packs ~15% smaller than row by row)
        for y in range(GH):
            data.append(sum((1 if px[x, y] > 110 else 0) << (x - x0) for x in range(x0, min(w, x0 + 8))))
    out.append((ch, w))
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "src", "font.h"), "w") as f:
    f.write("/* generated by tools/bake_font.py from Cinzel (OFL 1.1) - do not edit */\n")
    f.write("#define FONT_H %d\n#define FONT_TRACK %d\n#define FONT_SPACE 21\n" % (GH, TRACK))
    f.write('static const char font_chars[] = "%s";\n' % "".join(c for c, _ in out))
    f.write("static const unsigned char font_w[] = {%s};\n" % ",".join(str(w) for _, w in out))
    f.write("static const unsigned char font_bits[] = {\n")
    for i in range(0, len(data), 24):
        f.write(",".join(str(v) for v in data[i:i+24]) + ",\n")
    f.write("};\n")
    f.write("#define NLINES %d\nstatic const char *const txt_lines[NLINES] = {\n" % len(LINES))
    for s in LINES:
        f.write('  "%s",\n' % s)
    f.write("};\n")
print("glyphs:", len(out), "bytes:", len(data))
