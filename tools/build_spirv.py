#!/usr/bin/env python3
"""Compile the GLSL in src/shaders to SPIR-V (Vulkan 1.3) and embed it in src/spirv.h.
Every stage = common.glsl + its own file. Needs glslangValidator, spirv-opt, spirv-val
(Vulkan SDK on Windows, `apt install glslang-tools spirv-tools` on Ubuntu).
The generated header is committed, so building the intro itself needs none of them."""
import os, subprocess, struct, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import spv_byval, spv_renum, spv_sortdecl
here = os.path.dirname(os.path.abspath(__file__))
sd = os.environ.get("CATH_SHADERS", os.path.join(here, "..", "src", "shaders"))
STAGES = [  # file, stage, C name
    ("quad.vert", "vert", "spv_quad"), ("scene.frag", "frag", "spv_scene"), ("post.frag", "frag", "spv_post"),
    ("swarm.vert", "vert", "spv_swarm_vs"), ("swarm.frag", "frag", "spv_swarm_fs"),
    ("taa.frag", "frag", "spv_taa"), ("bake.comp", "comp", "spv_bake"),
]
# all compute work lives in ONE module (no duplicated helpers in the 64k): each
# file becomes main_<k>, selected by specialization constant 0 (MODE), with the
# workgroup size from constants 1-3. Order = the MODE numbers used by main.c.
COMP = ["bake_noise.comp", "bake_swarm.comp", "rt_verts.comp", "mesh_gen.comp", "bake_cloud.comp",
        "bake_planet.comp", "bake_pmap.comp", "chunks.comp", "camera.comp"]
import re
def merged():
    o = ["layout(constant_id=0) const int MODE=0;", "layout(local_size_x_id=1,local_size_y_id=2,local_size_z_id=3) in;"]
    for k, fn in enumerate(COMP):
        t = open(os.path.join(sd, fn)).read()
        t = re.sub(r"layout\(local_size[^)]*\) in;", "", t)
        names = set(re.findall(r"^\w+ (\w+)\(", t, re.M) + re.findall(r"^const \w+ (\w+)=", t, re.M) + re.findall(r"buffer (\w+)\{", t)) - {"main"}
        names = sorted(names)   # deterministic order (independent of PYTHONHASHSEED)
        o += ["#define %s %s_%d" % (n, n, k) for n in names]
        o.append(t.replace("void main(", "void main_%d(" % k))
        o += ["#undef %s" % n for n in names]
    o.append("void main(){\n" + "\n".join("  %sif(MODE==%d) main_%d();" % ("else " if k else "", k, k) for k in range(len(COMP))) + "\n}\n")
    return "\n".join(o)
# size-oriented pass list: SSA + DCE + simplification, but no exhaustive inlining (it bloats)
OPT = ("--eliminate-local-single-block --eliminate-local-single-store --ssa-rewrite --ccp "
       "--eliminate-dead-code-aggressive --merge-blocks --simplify-instructions --redundancy-elimination "
       "--remove-duplicates --eliminate-dead-code-aggressive --eliminate-dead-functions --compact-ids --strip-debug --strip-nonsemantic").split()
common = open(os.path.join(sd, "common.glsl")).read()
tmp = tempfile.mkdtemp()
out = ["/* generated by tools/build_spirv.py from src/shaders - do not edit */"]
total = 0
mods = []
import spvpack
for fn, st, name in STAGES:
    src = os.path.join(tmp, fn)
    hdr = common.replace("#version 460\n", "#version 460\n#define WR 1\n") if fn == "bake.comp" else common
    open(src, "w").write(hdr + (merged() if fn == "bake.comp" else open(os.path.join(sd, fn)).read()))
    raw, opt = src + ".spv", src + ".opt.spv"
    r = subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.3", "-S", st, src, "-o", raw], capture_output=True, text=True)
    if r.returncode: sys.exit(r.stdout + r.stderr)
    mid = src + ".mid.spv"
    subprocess.run(["spirv-opt", *OPT[:-3], raw, "-o", mid], check=True)
    d, _ = spv_byval.run(open(mid, "rb").read())   # 'in' params by value -> call-site temps vanish
    open(mid, "wb").write(d)
    subprocess.run(["spirv-opt", "--private-to-local", "--convert-local-access-chains", *OPT[:-3], "--if-conversion", *OPT, mid, "-o", opt], check=True)
    d = spv_renum.run(spv_sortdecl.run(open(opt, "rb").read()))   # hot declarations first, ids in definition order
    open(opt, "wb").write(d)
    subprocess.run(["spirv-val", "--target-env", "vulkan1.3", opt], check=True)
    total += len(d)
    mods.append(d)
    out.append("#define %s %d" % (name, len(mods) - 1))
    print("%-16s %7d bytes SPIR-V (spirv-val OK)" % (fn, len(d)))
# repack all modules into one SMOL-V style stream (decoded by unspv() in main.c)
blob, ofs = spvpack.encode_all(mods)
assert spvpack.decode_all(blob, ofs, len(mods)) == mods
used = set()
for m in mods:
    w = struct.unpack("<%dI" % (len(m) // 4), m); i = 5
    while i < len(w): used.add(w[i] & 0xffff); i += w[i] >> 16
nops = max(o for o in used if o < spvpack.NOPS) + 1
out.append("#define NSPV %d\n#define NOPS %d" % (len(mods), nops))
out.append("static const unsigned spv_ofs[%d] = {%s};" % (spvpack.NS, ",".join(map(str, ofs))))
out.append("static const unsigned char smol_ops[%d] = {%s};" % (nops, ",".join(str(x) for x in spvpack.OPS[:nops])))
out.append("static const unsigned char spv_pack[%d] = {" % len(blob))
for i in range(0, len(blob), 32):
    out.append(",".join(str(x) for x in blob[i:i+32]) + ",")
out.append("};")
open(os.environ.get("CATH_SPVH", os.path.join(here, "..", "src", "spirv.h")), "w").write("\n".join(out) + "\n")
import lzma
print("lzma(repacked):", len(lzma.compress(blob, preset=9 | lzma.PRESET_EXTREME)))
print("total SPIR-V:", total, " repacked:", len(blob))
# dev-build-only shaders (not part of the 64k, not repacked): src/spirv_dev.h
dv = ["/* generated by tools/build_spirv.py - DEV BUILD ONLY (not in the 64k release) */"]
for fn, name in [("dev_nancheck.comp", "spv_dev_nancheck")]:
    src = os.path.join(sd, fn); o = os.path.join(tmp, fn + ".spv")
    r = subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.3", src, "-o", o], capture_output=True, text=True)
    if r.returncode: sys.exit(r.stdout + r.stderr)
    subprocess.run(["spirv-opt", "-O", "--strip-debug", o, "-o", o], check=True)
    d = open(o, "rb").read(); w = struct.unpack("<%dI" % (len(d) // 4), d)
    dv.append("static const unsigned %s[%d] = {" % (name, len(w)))
    for i in range(0, len(w), 12): dv.append(",".join("0x%08x" % x for x in w[i:i+12]) + ",")
    dv.append("};")
open(os.path.join(here, "..", "src", "spirv_dev.h"), "w").write("\n".join(dv) + "\n")
